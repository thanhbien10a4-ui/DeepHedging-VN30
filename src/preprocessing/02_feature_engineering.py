"""Causal feature engineering for aligned VN30 / VN30F1M daily data.

Input (generated by 01_validate_and_align.py):
    data/processed/aligned_1d.csv

Outputs (generated, gitignored):
    data/processed/features_1d_full.csv
    data/processed/features_1d_model_ready.csv
    data/processed/feature_summary.json

Design principle:
- Every rolling feature at date t uses information available at or before t.
- No future shift/backfill is allowed.
- Scaling/standardization is NOT done here. It must be fit on the training fold only
  later to avoid leakage.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

TRADING_DAYS = 252

RAW_STATE_COLUMNS = [
    "spot_open", "spot_high", "spot_low", "spot_close", "spot_volume",
    "fut_open", "fut_high", "fut_low", "fut_close", "fut_volume",
]


def safe_zscore(series: pd.Series, window: int) -> pd.Series:
    mean = series.rolling(window).mean()
    std = series.rolling(window).std(ddof=1)
    return (series - mean) / std.replace(0, np.nan)


def add_market_features(df: pd.DataFrame, prefix: str) -> None:
    close = df[f"{prefix}_close"]
    high = df[f"{prefix}_high"]
    low = df[f"{prefix}_low"]
    open_ = df[f"{prefix}_open"]
    volume = df[f"{prefix}_volume"]
    log_ret = df[f"{prefix}_log_return"]

    # Momentum / cumulative log-return states.
    df[f"{prefix}_momentum_5"] = np.log(close / close.shift(5))
    df[f"{prefix}_momentum_20"] = np.log(close / close.shift(20))

    # Close-to-close realized volatility (annualized).
    df[f"{prefix}_realized_vol_5"] = (
        log_ret.rolling(5).std(ddof=1) * np.sqrt(TRADING_DAYS)
    )
    df[f"{prefix}_realized_vol_20"] = (
        log_ret.rolling(20).std(ddof=1) * np.sqrt(TRADING_DAYS)
    )

    # Garman-Klass range-based volatility (annualized).
    log_hl = np.log(high / low)
    log_co = np.log(close / open_)
    gk_daily_var = 0.5 * log_hl.pow(2) - (2 * np.log(2) - 1) * log_co.pow(2)

    for window in (5, 20):
        rolling_var = gk_daily_var.rolling(window).mean().clip(lower=0)
        df[f"{prefix}_gk_vol_{window}"] = np.sqrt(
            rolling_var * TRADING_DAYS
        )

    # Intraday range / close-position states.
    price_range = high - low
    df[f"{prefix}_range_pct"] = price_range / close
    df[f"{prefix}_close_location"] = (
        (close - low) / price_range.replace(0, np.nan)
    )

    # Volume/liquidity proxies. log1p handles zero volume safely.
    log_volume = np.log1p(volume)
    df[f"{prefix}_volume_log_change"] = log_volume.diff()
    df[f"{prefix}_volume_z20"] = safe_zscore(log_volume, 20)


def main() -> None:
    repo_root = Path(__file__).resolve().parents[2]
    processed_dir = repo_root / "data" / "processed"
    input_path = processed_dir / "aligned_1d.csv"

    if not input_path.exists():
        raise FileNotFoundError(
            f"Missing {input_path}. Run 01_validate_and_align.py first."
        )

    df = pd.read_csv(input_path)
    df["time"] = pd.to_datetime(df["time"], format="%Y-%m-%d", errors="raise")
    df = df.sort_values("time").reset_index(drop=True)

    # Recompute first-stage states defensively so this script is self-contained.
    df["spot_log_return"] = np.log(df["spot_close"]).diff()
    df["fut_log_return"] = np.log(df["fut_close"]).diff()
    df["basis_close"] = df["fut_close"] - df["spot_close"]
    df["basis_pct"] = df["basis_close"] / df["spot_close"]

    add_market_features(df, "spot")
    add_market_features(df, "fut")

    # Basis dynamics.
    df["basis_velocity_1"] = df["basis_pct"].diff()
    df["basis_z20"] = safe_zscore(df["basis_pct"], 20)

    # Cross-market dependence.
    df["return_corr_20"] = (
        df["spot_log_return"]
        .rolling(20)
        .corr(df["fut_log_return"])
    )

    # Rolling minimum-variance hedge ratio:
    # h_t = Cov(r_spot, r_fut) / Var(r_fut)
    # Uses only returns available up to and including t.
    rolling_cov = (
        df["spot_log_return"]
        .rolling(60)
        .cov(df["fut_log_return"])
    )
    rolling_var_fut = df["fut_log_return"].rolling(60).var(ddof=1)
    df["minvar_hedge_ratio_60"] = (
        rolling_cov / rolling_var_fut.replace(0, np.nan)
    )

    feature_columns = [
        "spot_log_return",
        "fut_log_return",
        "basis_close",
        "basis_pct",
        "spot_momentum_5",
        "spot_momentum_20",
        "spot_realized_vol_5",
        "spot_realized_vol_20",
        "spot_gk_vol_5",
        "spot_gk_vol_20",
        "spot_range_pct",
        "spot_close_location",
        "spot_volume_log_change",
        "spot_volume_z20",
        "fut_momentum_5",
        "fut_momentum_20",
        "fut_realized_vol_5",
        "fut_realized_vol_20",
        "fut_gk_vol_5",
        "fut_gk_vol_20",
        "fut_range_pct",
        "fut_close_location",
        "fut_volume_log_change",
        "fut_volume_z20",
        "basis_velocity_1",
        "basis_z20",
        "return_corr_20",
        "minvar_hedge_ratio_60",
    ]

    # Reject infinities explicitly.
    inf_counts = {
        col: int(np.isinf(df[col].to_numpy(dtype=float)).sum())
        for col in feature_columns
    }
    nonzero_inf = {k: v for k, v in inf_counts.items() if v != 0}
    if nonzero_inf:
        raise ValueError(f"Infinite feature values found: {nonzero_inf}")

    full_output = df[["time", *RAW_STATE_COLUMNS, *feature_columns]].copy()

    # Model-ready data starts only when all 60-day / shorter rolling states exist.
    model_ready = full_output.dropna(subset=feature_columns).reset_index(drop=True)

    full_path = processed_dir / "features_1d_full.csv"
    ready_path = processed_dir / "features_1d_model_ready.csv"
    summary_path = processed_dir / "feature_summary.json"

    full_output.to_csv(full_path, index=False, date_format="%Y-%m-%d")
    model_ready.to_csv(ready_path, index=False, date_format="%Y-%m-%d")

    nan_counts = {
        col: int(full_output[col].isna().sum()) for col in feature_columns
    }

    summary = {
        "input_rows": int(len(df)),
        "full_output_rows": int(len(full_output)),
        "model_ready_rows": int(len(model_ready)),
        "feature_count": int(len(feature_columns)),
        "max_lookback_trading_days": 60,
        "model_ready_date_min": model_ready["time"].min().strftime("%Y-%m-%d"),
        "model_ready_date_max": model_ready["time"].max().strftime("%Y-%m-%d"),
        "feature_columns": feature_columns,
        "nan_counts_before_drop": nan_counts,
        "infinite_counts": inf_counts,
        "leakage_policy": (
            "Features at t use only observations at or before t. "
            "No global scaling is performed in preprocessing; fit scalers on training folds only."
        ),
    }

    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)

    print("=" * 72)
    print("FEATURE ENGINEERING COMPLETE")
    print("=" * 72)
    print(f"Input rows        : {len(df):,}")
    print(f"Features created  : {len(feature_columns)}")
    print(f"Model-ready rows  : {len(model_ready):,}")
    print(f"Dropped warm-up   : {len(df) - len(model_ready):,}")
    print(f"From              : {model_ready['time'].min().date()}")
    print(f"To                : {model_ready['time'].max().date()}")
    print(f"Full dataset      : {full_path}")
    print(f"Model-ready       : {ready_path}")
    print(f"Feature report    : {summary_path}")


if __name__ == "__main__":
    main()
