"""Generate the final synthetic dataset from the frozen leakage-safe simulator.

This generator is the dataset source to use for downstream Deep Hedging training.
It supersedes the exploratory synthetic dataset generated by step 07.

Parameter provenance
--------------------
- Structural Heston parameters: TRAIN only, from step 10.
- Structural basis AR(1) parameters: TRAIN only, from step 10.
- Simulator hyperparameters: selected/tuned on VALIDATION and frozen in step 13.
- Real TEST data is never opened by this script.

Known limitation
----------------
The frozen standard-Heston simulator passed validation gates for volatility,
spot/futures correlation, basis dispersion, skewness and kurtosis, but retained
excess squared-return ACF(1) relative to validation. This limitation is recorded
in the output metadata and must not be silently removed by further validation
hyperparameter search.

Outputs
-------
data/synthetic/frozen/train.npz
data/synthetic/frozen/validation.npz
data/synthetic/frozen/test.npz
data/synthetic/frozen/metadata.json
results/figures/frozen_synthetic_sample_paths.png

The synthetic ``test`` split is only a Monte Carlo holdout from the simulator.
It is NOT the real 2025-2026 out-of-sample market test set.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

TRADING_DAYS = 252.0
SEED = 20261004
N_STEPS = 60
N_TRAIN = 20_000
N_VALIDATION = 4_000
N_TEST = 4_000


def gk_daily_variance(df: pd.DataFrame) -> pd.Series:
    log_hl = np.log(df["spot_high"] / df["spot_low"])
    log_co = np.log(df["spot_close"] / df["spot_open"])
    return (
        0.5 * log_hl.pow(2)
        - (2.0 * np.log(2.0) - 1.0) * log_co.pow(2)
    ).clip(lower=0.0)


def load_inputs(root: Path) -> tuple[dict, dict, dict, pd.DataFrame]:
    processed = root / "data" / "processed"
    calibration = processed / "calibration"

    heston_path = calibration / "train_heston_candidates.json"
    basis_path = calibration / "train_basis_params.json"
    frozen_path = calibration / "frozen_simulator_config.json"
    train_path = processed / "splits" / "train.csv"

    for path in (heston_path, basis_path, frozen_path, train_path):
        if not path.exists():
            raise FileNotFoundError(f"Missing required input: {path}")

    with open(heston_path, "r", encoding="utf-8") as f:
        heston_payload = json.load(f)
    with open(basis_path, "r", encoding="utf-8") as f:
        basis_payload = json.load(f)
    with open(frozen_path, "r", encoding="utf-8") as f:
        frozen_payload = json.load(f)

    train = pd.read_csv(train_path)
    train["time"] = pd.to_datetime(train["time"], errors="raise")
    train = train.sort_values("time").reset_index(drop=True)

    config = frozen_payload["frozen_config"]
    window = int(config["window"])
    matches = [r for r in heston_payload["results"] if int(r["window"]) == window]
    if len(matches) != 1:
        raise ValueError(f"Expected one TRAIN Heston candidate for window={window}.")

    heston = matches[0]
    basis = basis_payload["results"]["filtered"]
    return heston, basis, frozen_payload, train


def initial_state(
    train: pd.DataFrame,
    window: int,
    variance_scale: float,
) -> tuple[float, float, float]:
    s0 = float(train["spot_close"].iloc[-1])
    f0 = float(train["fut_close"].iloc[-1])
    b0 = float((f0 - s0) / s0)

    gk = gk_daily_variance(train)
    if window == 1:
        proxy = gk
    else:
        proxy = gk.rolling(window, min_periods=window).mean()

    v0_base = float(max(proxy.iloc[-1] * TRADING_DAYS, 1e-8))
    v0 = float(v0_base * variance_scale)
    return s0, v0, b0


def simulate_paths(
    rng: np.random.Generator,
    n_paths: int,
    n_steps: int,
    s0: float,
    v0: float,
    b0: float,
    heston: dict,
    basis_params: dict,
    config: dict,
) -> dict[str, np.ndarray]:
    mu = float(heston["mu"])
    kappa = float(heston["kappa"])

    variance_scale = float(config["variance_scale"])
    xi_scale = float(config["xi_scale"])
    rho_effective = float(config["rho_effective"])
    substeps = int(config["substeps"])

    theta = float(heston["theta"]) * variance_scale
    xi = float(heston["xi"]) * np.sqrt(variance_scale) * xi_scale
    rho = float(np.clip(rho_effective, -0.95, 0.95))

    c = float(basis_params["c"])
    phi = float(basis_params["phi"])
    sigma_b = (
        float(basis_params["residual_std_daily"])
        * float(config["basis_sigma_scale"])
    )

    spot = np.empty((n_paths, n_steps + 1), dtype=np.float32)
    variance = np.empty((n_paths, n_steps + 1), dtype=np.float32)
    basis = np.empty((n_paths, n_steps + 1), dtype=np.float32)
    futures = np.empty((n_paths, n_steps + 1), dtype=np.float32)

    spot[:, 0] = s0
    variance[:, 0] = v0
    basis[:, 0] = b0
    futures[:, 0] = s0 * (1.0 + b0)

    dt_sub = 1.0 / (TRADING_DAYS * substeps)
    sqrt_dt_sub = np.sqrt(dt_sub)
    rho_ind_scale = np.sqrt(max(1.0 - rho * rho, 0.0))

    for day in range(n_steps):
        s = spot[:, day].astype(np.float64)
        v = variance[:, day].astype(np.float64)

        for _ in range(substeps):
            z_s = rng.standard_normal(n_paths)
            z_i = rng.standard_normal(n_paths)
            z_v = rho * z_s + rho_ind_scale * z_i

            v_pos = np.maximum(v, 0.0)
            v_next = (
                v
                + kappa * (theta - v_pos) * dt_sub
                + xi * np.sqrt(v_pos) * sqrt_dt_sub * z_v
            )
            v_next = np.maximum(v_next, 0.0)

            s = s * np.exp(
                (mu - 0.5 * v_pos) * dt_sub
                + np.sqrt(v_pos) * sqrt_dt_sub * z_s
            )
            v = v_next

        z_b = rng.standard_normal(n_paths)
        b_next = c + phi * basis[:, day].astype(np.float64) + sigma_b * z_b
        b_next = np.maximum(b_next, -0.95)
        f_next = s * (1.0 + b_next)

        spot[:, day + 1] = s.astype(np.float32)
        variance[:, day + 1] = v.astype(np.float32)
        basis[:, day + 1] = b_next.astype(np.float32)
        futures[:, day + 1] = f_next.astype(np.float32)

    spot_log_return = np.diff(np.log(spot.astype(np.float64)), axis=1).astype(np.float32)
    fut_log_return = np.diff(np.log(futures.astype(np.float64)), axis=1).astype(np.float32)

    return {
        "spot": spot,
        "variance": variance,
        "basis": basis,
        "futures": futures,
        "spot_log_return": spot_log_return,
        "fut_log_return": fut_log_return,
    }


def squared_return_acf1(returns: np.ndarray) -> float:
    x = returns[:, :-1].astype(np.float64) ** 2
    y = returns[:, 1:].astype(np.float64) ** 2
    return float(np.corrcoef(x.ravel(), y.ravel())[0, 1])


def summarize(arrays: dict[str, np.ndarray]) -> dict:
    sr = arrays["spot_log_return"].astype(np.float64)
    fr = arrays["fut_log_return"].astype(np.float64)
    basis = arrays["basis"].astype(np.float64)[:, 1:]
    return {
        "n_paths": int(sr.shape[0]),
        "n_steps": int(sr.shape[1]),
        "spot_return_mean_daily": float(np.mean(sr)),
        "spot_return_std_daily": float(np.std(sr, ddof=1)),
        "futures_return_mean_daily": float(np.mean(fr)),
        "futures_return_std_daily": float(np.std(fr, ddof=1)),
        "spot_futures_return_corr": float(np.corrcoef(sr.ravel(), fr.ravel())[0, 1]),
        "basis_mean": float(np.mean(basis)),
        "basis_std": float(np.std(basis, ddof=1)),
        "spot_squared_return_acf1": squared_return_acf1(sr),
        "variance_mean": float(np.mean(arrays["variance"])),
        "variance_zero_fraction": float(np.mean(arrays["variance"] <= 0.0)),
    }


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    out_dir = root / "data" / "synthetic" / "frozen"
    figures_dir = root / "results" / "figures"
    out_dir.mkdir(parents=True, exist_ok=True)
    figures_dir.mkdir(parents=True, exist_ok=True)

    heston, basis_params, frozen_payload, train = load_inputs(root)
    config = frozen_payload["frozen_config"]
    window = int(config["window"])

    s0, v0, b0 = initial_state(
        train=train,
        window=window,
        variance_scale=float(config["variance_scale"]),
    )

    rng = np.random.default_rng(SEED)
    split_sizes = {
        "train": N_TRAIN,
        "validation": N_VALIDATION,
        "test": N_TEST,
    }

    summaries: dict[str, dict] = {}
    first_train_arrays: dict[str, np.ndarray] | None = None

    for split_name, n_paths in split_sizes.items():
        arrays = simulate_paths(
            rng=rng,
            n_paths=n_paths,
            n_steps=N_STEPS,
            s0=s0,
            v0=v0,
            b0=b0,
            heston=heston,
            basis_params=basis_params,
            config=config,
        )
        np.savez_compressed(out_dir / f"{split_name}.npz", **arrays)
        summaries[split_name] = summarize(arrays)
        if split_name == "train":
            first_train_arrays = arrays

    limitation = {
        "validation_metric": "spot squared-return ACF(1)",
        "validation_target": float(
            frozen_payload["validation_target"]["spot_squared_acf1"]
        ),
        "frozen_validation_synthetic": float(
            frozen_payload["frozen_metrics"]["spot_sq_acf1_syn"]
        ),
        "gate_passed": bool(
            frozen_payload["gates"]["spot_sq_acf1_abs_diff_le_0.10"]
        ),
        "note": (
            "Standard Heston baseline retains excess volatility clustering. "
            "No further validation hyperparameter search is permitted after freezing."
        ),
    }

    metadata = {
        "dataset_role": "final_frozen_synthetic_for_deep_hedging_training",
        "seed": SEED,
        "n_steps": N_STEPS,
        "split_sizes": split_sizes,
        "real_test_data_used": False,
        "parameter_provenance": {
            "heston_structural": "train_only",
            "basis_structural": "train_only",
            "simulator_hyperparameters": "validation_tuned_then_frozen",
        },
        "initial_state_source": "last observation of real TRAIN split",
        "initial_state": {
            "spot": s0,
            "variance": v0,
            "basis": b0,
            "train_date": train["time"].iloc[-1].strftime("%Y-%m-%d"),
        },
        "heston_train_parameters": {
            "window": window,
            "mu": float(heston["mu"]),
            "kappa": float(heston["kappa"]),
            "theta_unscaled": float(heston["theta"]),
            "xi_unscaled": float(heston["xi"]),
            "rho_unscaled": float(heston["rho"]),
        },
        "frozen_config": config,
        "effective_heston_parameters": {
            "theta": float(heston["theta"]) * float(config["variance_scale"]),
            "xi": (
                float(heston["xi"])
                * np.sqrt(float(config["variance_scale"]))
                * float(config["xi_scale"])
            ),
            "rho": float(config["rho_effective"]),
            "substeps_per_trading_day": int(config["substeps"]),
        },
        "effective_basis_parameters": {
            "c": float(basis_params["c"]),
            "phi": float(basis_params["phi"]),
            "innovation_std_daily": (
                float(basis_params["residual_std_daily"])
                * float(config["basis_sigma_scale"])
            ),
        },
        "known_limitation": limitation,
        "synthetic_split_summaries": summaries,
        "warning": (
            "The synthetic test split is a simulator holdout only. It must not be confused "
            "with the untouched real 2025-2026 OOS test set."
        ),
    }

    metadata_path = out_dir / "metadata.json"
    with open(metadata_path, "w", encoding="utf-8") as f:
        json.dump(metadata, f, ensure_ascii=False, indent=2, allow_nan=False)

    if first_train_arrays is None:
        raise RuntimeError("Train arrays were not generated.")

    fig = plt.figure(figsize=(12, 5))
    n_plot = min(20, first_train_arrays["spot"].shape[0])
    for i in range(n_plot):
        normalized = first_train_arrays["spot"][i] / first_train_arrays["spot"][i, 0]
        plt.plot(normalized, linewidth=0.7, alpha=0.7)
    plt.title("Frozen Simulator: Sample Synthetic VN30 Spot Paths")
    plt.xlabel("Trading day")
    plt.ylabel("S_t / S_0")
    plt.tight_layout()
    figure_path = figures_dir / "frozen_synthetic_sample_paths.png"
    fig.savefig(figure_path, dpi=160)
    plt.close(fig)

    print("=" * 96)
    print("FINAL FROZEN SYNTHETIC DATA GENERATION COMPLETE")
    print("=" * 96)
    print(f"Seed                : {SEED}")
    print(f"Horizon             : {N_STEPS} trading days")
    print(f"Train paths         : {N_TRAIN:,}")
    print(f"Validation paths    : {N_VALIDATION:,}")
    print(f"Test paths          : {N_TEST:,} (synthetic holdout, NOT real OOS)")
    print(f"Initial state date  : {train['time'].iloc[-1].date()}")
    print(f"S0                  : {s0:.6f}")
    print(f"v0 scaled           : {v0:.6f}")
    print(f"basis0              : {b0:.6f}")
    print(f"Heston window       : {window}d")
    print(f"variance scale      : {float(config['variance_scale']):.6f}")
    print(f"xi scale            : {float(config['xi_scale']):.6f}")
    print(f"rho effective       : {float(config['rho_effective']):.6f}")
    print(f"substeps/day        : {int(config['substeps'])}")
    print(f"basis sigma scale   : {float(config['basis_sigma_scale']):.6f}")
    print()

    for split_name, summary in summaries.items():
        print(
            f"{split_name:10s} | "
            f"spot std={summary['spot_return_std_daily']:.5f} | "
            f"fut std={summary['futures_return_std_daily']:.5f} | "
            f"corr={summary['spot_futures_return_corr']:.4f} | "
            f"basis std={summary['basis_std']:.5f} | "
            f"sqACF1={summary['spot_squared_return_acf1']:.4f}"
        )

    print()
    print("KNOWN LIMITATION:")
    print(
        "Standard Heston retains excess volatility clustering on validation: "
        f"target ACF1={limitation['validation_target']:.4f}, "
        f"frozen synthetic={limitation['frozen_validation_synthetic']:.4f}."
    )
    print()
    print(f"Synthetic data dir : {out_dir}")
    print(f"Metadata           : {metadata_path}")
    print(f"Figure             : {figure_path}")
    print("REAL TEST DATA WAS NOT READ.")


if __name__ == "__main__":
    main()
